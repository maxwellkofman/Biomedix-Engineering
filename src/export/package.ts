const ps = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function powershellScript(o: PackageOptions): string {
  const folders = folderPaths(o.tree);
  return `﻿<#
  Creates the ${o.libraryName} document library for your QMS in SharePoint Online and uploads the
  documents in this folder as drafts.

  Prerequisites (PowerShell 7):
    Install-Module PnP.PowerShell -Scope CurrentUser
    Register-PnPEntraIDAppForInteractiveLogin -ApplicationName "QMS setup" -Tenant <yourtenant>.onmicrosoft.com
      (copy the client ID it prints)

  Run from the unzipped folder:
    ./Setup-SharePoint-QMS.ps1 -SiteUrl ${o.siteUrl || 'https://<yourtenant>.sharepoint.com/sites/QMS'} -ClientId <client id>

  Existing files are never overwritten.
#>
param(
  [string] $SiteUrl = ${ps(o.siteUrl || '')},
  [Parameter(Mandatory = $true)] [string] $ClientId,
  [string] $LibraryName = ${ps(o.libraryName)}
)
$ErrorActionPreference = 'Stop'
if (-not $SiteUrl) { throw 'Pass -SiteUrl https://<yourtenant>.sharepoint.com/sites/<site>' }
$Root = $PSScriptRoot

Connect-PnPOnline -Url $SiteUrl -Interactive -ClientId $ClientId

# 1. Library with major and minor versions, so uploads arrive as drafts (0.1)
$list = Get-PnPList -Identity $LibraryName -ErrorAction SilentlyContinue
if (-not $list) {
  Write-Host "Creating library $LibraryName"
  $list = New-PnPList -Title $LibraryName -Template DocumentLibrary -OnQuickLaunch
}
Set-PnPList -Identity $LibraryName -EnableVersioning $true -MajorVersions 500 -EnableMinorVersions $true -MinorVersions 100 | Out-Null

# 2. Document control columns
function Add-QmsField($Name, $Display, $Type, $Choices) {
  if (Get-PnPField -List $LibraryName -Identity $Name -ErrorAction SilentlyContinue) { return }
  if ($Type -eq 'Choice') {
    Add-PnPField -List $LibraryName -InternalName $Name -DisplayName $Display -Type Choice -Choices $Choices -AddToDefaultView | Out-Null
  } else {
    Add-PnPField -List $LibraryName -InternalName $Name -DisplayName $Display -Type $Type -AddToDefaultView | Out-Null
  }
}
Add-QmsField 'DocumentID' 'Document ID' 'Text'
Add-QmsField 'Revision' 'Revision' 'Text'
Add-QmsField 'DocStatus' 'Status' 'Choice' @('Draft', 'In review', 'Approved', 'Effective', 'Obsolete')
Add-QmsField 'ProcessOwner' 'Process owner' 'Text'
Add-QmsField 'EffectiveDate' 'Effective date' 'DateTime'

# 3. Folders
$web = Get-PnPWeb
$rootFolder = Get-PnPProperty -ClientObject $list -Property RootFolder
$libPath = $rootFolder.ServerRelativeUrl.Substring($web.ServerRelativeUrl.TrimEnd('/').Length).TrimStart('/')
$folders = @(
${folders.map((f) => `  ${ps(f)}`).join(',\n')}
)
foreach ($f in $folders) {
  Resolve-PnPFolder -SiteRelativePath "$libPath/$f" | Out-Null
  Write-Host "Folder  $f"
}

# 4. Upload documents as drafts; skip anything already there
Get-ChildItem -Path $Root -Recurse -File |
  Where-Object { $_.Extension -in '.docx', '.csv' } |
  ForEach-Object {
    $rel = [IO.Path]::GetRelativePath($Root, $_.DirectoryName).Replace('\\', '/')
    $target = "$libPath/$rel"
    if (Get-PnPFile -Url "$target/$($_.Name)" -ErrorAction SilentlyContinue) {
      Write-Host "Skipped $rel/$($_.Name) (already exists)"
      return
    }
    $values = @{ Revision = 'A'; DocStatus = 'Draft' }
    if ($_.BaseName -match '^(\\S+)\\s') { $values.DocumentID = $Matches[1] }
    Add-PnPFile -Path $_.FullName -Folder $target -Values $values | Out-Null
    Write-Host "Uploaded $rel/$($_.Name)"
  }

# 5. Require check-out from now on
Set-PnPList -Identity $LibraryName -ForceCheckout $true | Out-Null

Write-Host ''
Write-Host "Done. Next: give edit rights only to document control, and validate the library under SOP-014."
`;
}

/** Build every file in the tree. Word documents are generated here. */
export async function buildFiles(o: PackageOptions, onProgress?: (done: number, total: number) => void): Promise<BuiltFile[]> {
  const entries = filePaths(o.tree);
  const out: BuiltFile[] = [];
  let done = 0;
  for (const { dir, file } of entries) {
    out.push({ dir, name: file.name, blob: await render(file, o), meta: metaFor(file, o.tokens) });
    onProgress?.(++done, entries.length);
  }
  return out;
}

function metaFor(file: QmsFile, tokens: TokenValues): BuiltFile['meta'] {
  if (file.kind !== 'doc') return undefined;
  return {
    DocumentID: file.doc.proc.id,
    Revision: 'A',
    DocStatus: 'Draft',
    ProcessOwner: tokens[file.doc.ownerToken]?.value ?? '',
  };
}

async function render(file: QmsFile, o: PackageOptions): Promise<Blob> {
  switch (file.kind) {
    case 'doc':
      return docToDocx(file.doc, o.tokens);
    case 'gate-zero':
      return gateZeroDocx(o.suite, o.tokens);
    case 'master-list':
      return new Blob([masterListCsv(o)], { type: 'text/csv;charset=utf-8' });
    case 'readme':
      return new Blob([readmeText(o)], { type: 'text/plain;charset=utf-8' });
  }
}

/** The whole library as a ZIP, with empty folders kept and the setup script at the top. */
export async function buildZip(o: PackageOptions, onProgress?: (done: number, total: number) => void): Promise<Blob> {
  const { default: JSZip } = await import('jszip');
  const zip = new JSZip();
  const root = zip.folder(o.tree.name)!;
  folderPaths(o.tree).forEach((p) => root.folder(p));
  const files = await buildFiles(o, onProgress);
  files.forEach((f) => root.file(f.dir ? `${f.dir}/${f.name}` : f.name, f.blob));
  root.file('Setup-SharePoint-QMS.ps1', powershellScript(o));
  return zip.generateAsync({ type: 'blob', compression: 'DEFLATE' });
}

export function downloadBlob(filename: string, blob: Blob) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
