/**
 * Turns the QMS tree into real files: Word documents, the master document
 * list, a README and the SharePoint setup script. Used by the ZIP download
 * and the direct SharePoint upload.
 */
import { TOKENS, type TokenValues } from '../intake/derive';
import type { Suite } from '../templates/generate';
import { docToDocx, gateZeroDocx } from './docx';
import { filePaths, folderPaths, type QmsFile, type QmsFolder } from './structure';

export const DOCX_TYPE = 'application/vnd.openxmlformats-officedocument.wordprocessingml.document';

export interface PackageOptions {
  suite: Suite;
  tokens: TokenValues;
  tree: QmsFolder;
  siteUrl: string;
  libraryName: string;
}

export interface BuiltFile {
  dir: string;
  name: string;
  blob: Blob;
  /** SharePoint column values for documents. */
  meta?: { DocumentID: string; Revision: string; DocStatus: string; ProcessOwner: string };
}

const csvCell = (v: string) => `"${v.replace(/"/g, '""')}"`;

export function masterListCsv(o: PackageOptions): string {
  const rows = [['Document ID', 'Title', 'Revision', 'Status', 'Process owner', 'Location']];
  filePaths(o.tree).forEach(({ dir, file }) => {
    if (file.kind !== 'doc') return;
    const owner = o.tokens[file.doc.ownerToken]?.value ?? `[${TOKENS[file.doc.ownerToken].label}]`;
    rows.push([file.doc.proc.id, file.doc.proc.title, 'A', 'Draft', owner, `${dir}/${file.name}`]);
  });
  // Excel opens UTF-8 CSV correctly only with a byte-order mark.
  return '﻿' + rows.map((r) => r.map(csvCell).join(',')).join('\r\n') + '\r\n';
}

